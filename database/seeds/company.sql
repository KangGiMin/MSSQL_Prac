CREATE TABLE dbo.DEPT (DEPTNO INT CONSTRAINT PK_DEPT PRIMARY KEY, DNAME NVARCHAR(30) NOT NULL, LOC NVARCHAR(30));
CREATE TABLE dbo.EMP (
 EMPNO INT CONSTRAINT PK_EMP PRIMARY KEY, ENAME NVARCHAR(30) NOT NULL, JOB NVARCHAR(30),
 MGR INT NULL, HIREDATE DATE NOT NULL, SAL DECIMAL(12,2) NOT NULL, COMM DECIMAL(12,2) NULL,
 DEPTNO INT CONSTRAINT FK_EMP_DEPT REFERENCES dbo.DEPT(DEPTNO)
);
